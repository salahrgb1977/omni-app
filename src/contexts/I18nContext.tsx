const I18nContext = createContext<I18nContextType | undefined>(undefined)

const LANG_STORAGE_KEY = 'omni_hvac_language'

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // Arabic is primary / default as specified by user
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(LANG_STORAGE_KEY) as Language
    return saved === 'en' ? 'en' : 'ar'
  })

  const direction: Direction = language === 'ar' ? 'rtl' : 'ltr'
  const isRTL = direction === 'rtl'

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = direction
    localStorage.setItem(LANG_STORAGE_KEY, language)
  }, [language, direction])

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
  }

  const t = (key: string, defaultText?: string): string => {
    const langDict = translations[language] || translations.ar
    if (langDict && langDict[key]) {
      return langDict[key]
    }
    const fallbackDict = translations.en
    if (fallbackDict && fallbackDict[key]) {
      return fallbackDict[key]
    }
    return defaultText || key
  }

  return (
    <I18nContext.Provider value={{ language, direction, setLanguage, t, isRTL }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18n must be used within an I18nProvider')
  }
  return context
}
